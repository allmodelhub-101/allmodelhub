import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const base = process.env.ANDROID_WEB_BASE || 'http://localhost:3105';
if (!['localhost','127.0.0.1'].includes(new URL(base).hostname)) throw new Error('This essential check must run against a local production build.');
const out = 'docs/android/verification';
const screenshots = 'docs/android/store/assets/screenshots';
await fs.mkdir(out,{recursive:true}); await fs.mkdir(screenshots,{recursive:true});
const browser = await chromium.launch();
const context = await browser.newContext({viewport:{width:360,height:640},deviceScaleFactor:3,isMobile:true,hasTouch:true,serviceWorkers:'allow'});
const page = await context.newPage();
const errors=[]; page.on('pageerror',error=>errors.push(error.message));
const checks=[];
try {
  await page.goto(`${base}/android`,{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:/Your AI workspace/}).waitFor();
  assert.equal(await page.getByRole('link',{name:/Download APK/}).count(),0);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  const manifest=await (await context.request.get(`${base}/manifest.webmanifest`)).json();
  assert.equal(manifest.display,'standalone'); assert.equal(manifest.scope,'/'); assert.equal(manifest.id,'/');
  assert.equal(manifest.start_url,'/chat');
  for(const size of ['192x192','512x512']) assert.ok(manifest.icons.some(icon=>icon.sizes===size&&icon.purpose==='any'));
  assert.ok(manifest.icons.some(icon=>icon.purpose==='maskable'&&icon.sizes==='512x512'));
  for(const icon of manifest.icons) assert.equal((await context.request.get(base+icon.src)).status(),200);
  checks.push('Manifest and explicit-sized icon endpoints pass; unpublished APK CTA absent.');
  const sw=await context.request.get(`${base}/sw.js`); assert.match(sw.headers()['cache-control'],/no-store/);
  await page.evaluate(async()=>{ await navigator.serviceWorker.ready; if(!navigator.serviceWorker.controller) await new Promise(resolve=>navigator.serviceWorker.addEventListener('controllerchange',resolve,{once:true})); });
  await page.evaluate(async()=>{ const r=await fetch('/manifest.webmanifest'); await r.text(); });
  const cacheEntries=await page.evaluate(async()=>Object.fromEntries(await Promise.all((await caches.keys()).map(async name=>[name,(await (await caches.open(name)).keys()).map(r=>new URL(r.url).pathname)]))));
  assert.deepEqual(Object.keys(cacheEntries),['models-suite-public-offline-v1']); assert.deepEqual(cacheEntries['models-suite-public-offline-v1'],['/offline.html']);
  checks.push('Production service worker controls page; CacheStorage contains only public offline HTML.');
  // Exercise browser event handling only; no OS installation is claimed.
  await page.evaluate(()=>{window.__promptCalls=0;const event=new Event('beforeinstallprompt',{cancelable:true});Object.assign(event,{prompt:async()=>{window.__promptCalls++;},userChoice:Promise.resolve({outcome:'accepted'})});window.dispatchEvent(event);});
  await page.getByRole('button',{name:'Install from Chrome',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Installation accepted'}).waitFor();
  assert.equal(await page.evaluate(()=>window.__promptCalls),1);
  checks.push('Install button calls one-shot browser prompt and reports acceptance (synthetic browser event, not device installation).');
  // Capture the real default page, not the synthetic prompt outcome.
  await page.reload({waitUntil:'networkidle'});
  await page.screenshot({path:`${out}/android-360-light.png`,fullPage:true});
  await page.screenshot({path:`${screenshots}/android-download-1080x1920.png`});
  await page.evaluate(()=>{document.documentElement.dataset.theme='dark';localStorage.setItem('amh-theme','dark');});
  await page.screenshot({path:`${out}/android-360-dark.png`,fullPage:true});
  await context.setOffline(true);
  await page.goto(`${base}/chat`,{waitUntil:'load'});
  await page.getByRole('heading',{name:'Your workspace is a connection away.'}).waitFor();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:`${out}/offline-360.png`});
  const api=await page.evaluate(async()=>{try{await fetch('/api/android-offline-check');return 'unexpected-success';}catch{return 'network-failure';}});
  assert.equal(api,'network-failure');
  const auth=await page.goto(`${base}/auth/login`,{waitUntil:'load'}).then(()=>false,()=>true); assert.equal(auth,true);
  checks.push('Offline navigation shows reconnect page; API and auth navigation are not replaced by cached app/private responses.');
  await context.setOffline(false);
  await page.goto(`${base}/auth/login`,{waitUntil:'networkidle'});
  await page.screenshot({path:`${screenshots}/sign-in-1080x1920.png`});
  await page.goto(base,{waitUntil:'networkidle'});
  await page.screenshot({path:`${screenshots}/homepage-1080x1920.png`});
  await page.setViewportSize({width:1366,height:900});
  await page.goto(`${base}/android`,{waitUntil:'networkidle'});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:`${out}/android-desktop.png`,fullPage:true});
  assert.deepEqual(errors,[]);
  checks.push('Public download, homepage and sign-in screenshot candidates captured; mobile/desktop download has no overflow or page errors.');
  await fs.writeFile(`${out}/web-results.json`,JSON.stringify({status:'PASS',base,checks,errors,manifest,cacheEntries,deviceInstall:'UNAVAILABLE: no connected Android device/emulator',screenshots:'Real public web renders; not installed Android app screenshots'},null,2)+'\n');
  console.log(`${checks.length} essential PWA checks passed; screenshots saved under ${out}.`);
} finally {await browser.close();}
